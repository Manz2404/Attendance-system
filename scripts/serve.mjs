import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { loadLocalEnvironment } from './database.mjs';
import { serverOptions } from '../lib/server-options.mjs';
loadLocalEnvironment();
const { port, mode, host, env, cloud } = serverOptions(process.env, process.argv[2]);
console.log(cloud ? `Starting Hadir Attendance on ${host}:${port} behind your host's HTTPS endpoint.` : `Open http://127.0.0.1:${port} in your browser. Keep this window open; press Ctrl+C to stop.`);
const require = createRequire(import.meta.url);
const child = spawn(process.execPath, [require.resolve('next/dist/bin/next'), mode, '--hostname', host, '--port', String(port)], { stdio: 'inherit', env });
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 0; });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
